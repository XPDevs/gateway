int cp_is_word(uint32_t cp)
{
    if (cp < 0x80)
        return (cp >= '0' && cp <= '9') || (cp >= 'a' && cp <= 'z') ||
               (cp >= 'A' && cp <= 'Z') || cp == '_';
    size_t lo = 0, hi = sizeof(WORD_RANGES) / sizeof(WORD_RANGES[0]);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < WORD_RANGES[mid][0]) hi = mid;
        else if (cp > WORD_RANGES[mid][1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}

uint32_t utf8_next(const unsigned char **pp)
{
    const unsigned char *p = *pp;
    uint32_t cp;
    if (p[0] < 0x80) { cp = p[0]; *pp = p + 1; return cp; }
    if ((p[0] & 0xE0) == 0xC0 && p[1]) {
        cp = ((uint32_t)(p[0] & 0x1F) << 6) | (uint32_t)(p[1] & 0x3F);
        *pp = p + 2;
        return cp;
    }
    if ((p[0] & 0xF0) == 0xE0 && p[1] && p[2]) {
        cp = ((uint32_t)(p[0] & 0x0F) << 12) | ((uint32_t)(p[1] & 0x3F) << 6) |
             (uint32_t)(p[2] & 0x3F);
        *pp = p + 3;
        return cp;
    }
    if ((p[0] & 0xF8) == 0xF0 && p[1] && p[2] && p[3]) {
        cp = ((uint32_t)(p[0] & 0x07) << 18) | ((uint32_t)(p[1] & 0x3F) << 12) |
             ((uint32_t)(p[2] & 0x3F) << 6) | (uint32_t)(p[3] & 0x3F);
        *pp = p + 4;
        return cp;
    }
    *pp = p + 1;
    return 0xFFFD;
}

/* len(re.findall(r"\w+", text)) */
int count_words(const char *text)
{
    int count = 0;
    int in_word = 0;
    const unsigned char *p = (const unsigned char *)text;
    while (*p) {
        uint32_t cp = utf8_next(&p);
        if (cp_is_word(cp)) {
            if (!in_word) { count++; in_word = 1; }
        } else {
            in_word = 0;
        }
    }
    return count;
}

int reading_time_minutes(int wc, int wpm)
{
    if (wc <= 0) return 0;
    long v = py_round_long((double)wc / (double)wpm);
    return v < 1 ? 1 : (int)v;
}

