void dedupe_paragraphs(vec_t *paras, size_t max_keep)
{
    map_t seen;
    map_init(&seen);
    vec_t out;
    vec_init(&out);
    for (size_t i = 0; i < paras->len; i++) {
        char *p = paras->items[i];
        char hex[33];
        md5_hex(p, strlen(p), hex);
        if (map_has(&seen, hex)) { free(p); continue; }
        map_put(&seen, hex, (void *)1);
        vec_push(&out, p);
        if (out.len >= max_keep) {
            for (size_t k = i + 1; k < paras->len; k++) free(paras->items[k]);
            break;
        }
    }
    free(paras->items);
    *paras = out;
    map_free(&seen, NULL);
}

