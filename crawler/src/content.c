char *detect_language_from_text(const char *text, size_t sample)
{
    if (!text) return xstrdup("");
    size_t chars = 0;
    size_t i = 0;
    while (text[i] && chars < sample) {
        i++;
        while (text[i] && ((unsigned char)text[i] & 0xC0) == 0x80) i++;
        chars++;
    }
    char *head = xstrndup(text, i);
    for (char *p = head; *p; p++) *p = (char)tolower((unsigned char)*p);

    map_t sw;
    stopword_set_init(&sw);
    long words = 0, hits = 0;
    size_t n = strlen(head);
    size_t k = 0;
    while (k < n) {
        if (head[k] >= 'a' && head[k] <= 'z') {
            size_t start = k;
            while (k < n && head[k] >= 'a' && head[k] <= 'z') k++;
            size_t wlen = k - start;
            if (wlen >= 2) {
                words++;
                char *w = xstrndup(head + start, wlen);
                if (map_has(&sw, w)) hits++;
                free(w);
            }
        } else {
            k++;
        }
    }
    map_free(&sw, NULL);
    free(head);
    if (words == 0) return xstrdup("");
    double ratio = (double)hits / (double)words;
    return xstrdup(ratio > 0.05 ? "en" : "");
}

char *pick_description(meta_parser *m, vec_t *paragraphs)
{
    const char *sources[3] = { m->description, m->og_description, m->twitter_description };
    for (int i = 0; i < 3; i++) {
        if (sources[i] && *sources[i]) {
            char *collapsed = collapse_ws_trim(sources[i]);
            if (*collapsed) {
                char *out = trunc_chars(collapsed, DESC_MAX_LEN);
                free(collapsed);
                return out;
            }
            free(collapsed);
        }
    }
    for (size_t i = 0; i < paragraphs->len; i++) {
        char *p = paragraphs->items[i];
        if (utf8_len(p) >= 80) return trunc_chars(p, DESC_MAX_LEN);
    }
    if (paragraphs->len) return trunc_chars((char *)paragraphs->items[0], DESC_MAX_LEN);
    return xstrdup("");
}

