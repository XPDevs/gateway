char *decode_body(const unsigned char *body, size_t len, const char *enc)
{
    char *low = str_lower(enc ? enc : "utf-8");
    const unsigned char *src = body;
    size_t srclen = len;
    int strip_bom = 0;
    if (!strcmp(low, "utf-8-sig")) {
        strip_bom = 1;
        free(low);
        low = xstrdup("utf-8");
    }
    if (strip_bom && srclen >= 3 && src[0] == 0xEF && src[1] == 0xBB && src[2] == 0xBF) {
        src += 3;
        srclen -= 3;
    }
    const char *ic = iconv_alias(low);
    iconv_t cd = iconv_open("UTF-8", ic ? ic : "UTF-8");
    if (cd == (iconv_t)-1) cd = iconv_open("UTF-8", "ISO-8859-1");
    if (cd == (iconv_t)-1) {
        char *out = xmalloc(srclen + 1);
        memcpy(out, src, srclen);
        out[srclen] = '\0';
        free(low);
        return out;
    }
    size_t cap = srclen * 3 + 32;
    char *out = xmalloc(cap);
    size_t outlen = 0;
    char *inptr = (char *)src;
    size_t inleft = srclen;
    while (inleft > 0) {
        if (outlen + 8 > cap) {
            cap = cap * 2 + 32;
            out = xrealloc(out, cap);
        }
        char *optr = out + outlen;
        size_t oleft = cap - outlen - 4;
        size_t rc = iconv(cd, &inptr, &inleft, &optr, &oleft);
        outlen = (size_t)(optr - out);
        if (rc == (size_t)-1) {
            if (errno == E2BIG) continue;
            if (errno == EILSEQ || errno == EINVAL) {
                if (outlen + 4 > cap) { cap = cap * 2 + 32; out = xrealloc(out, cap); }
                memcpy(out + outlen, "\xEF\xBF\xBD", 3);
                outlen += 3;
                inptr++;
                inleft--;
                continue;
            }
            break;
        }
    }
    out[outlen] = '\0';
    iconv_close(cd);
    free(low);
    return out;
}

char *detect_encoding(const unsigned char *body, size_t len, const char *header_charset)
{
    if (header_charset && *header_charset && encoding_known(header_charset))
        return xstrdup(header_charset);
    if (len >= 3 && body[0] == 0xEF && body[1] == 0xBB && body[2] == 0xBF) return xstrdup("utf-8-sig");
    if (len >= 2 && body[0] == 0xFF && body[1] == 0xFE) return xstrdup("utf-16-le");
    if (len >= 2 && body[0] == 0xFE && body[1] == 0xFF) return xstrdup("utf-16-be");

    size_t window = len < 4096 ? len : 4096;

    for (size_t i = 0; i + 6 <= window; i++) {
        if (strncasecmp((const char *)body + i, "<meta", 5) != 0) continue;
        size_t j = i + 5;
        if (j < window && body[j] == '>') continue;
        while (j < window && body[j] != '>') j++;
        if (j >= window) continue;
        for (size_t k = i + 5; k + 7 < j; k++) {
            if (strncasecmp((const char *)body + k, "charset", 7) != 0) continue;
            size_t q = k + 7;
            while (q < j && is_space_byte((unsigned char)body[q])) q++;
            if (q >= j || body[q] != '=') continue;
            q++;
            while (q < j && is_space_byte((unsigned char)body[q])) q++;
            if (q < j && (body[q] == '"' || body[q] == '\'')) q++;
            size_t vs = q;
            while (q < j && (isalnum((unsigned char)body[q]) || body[q] == '-' || body[q] == '_')) q++;
            if (q > vs) {
                char *enc = xstrndup((const char *)body + vs, q - vs);
                char *low = str_lower(enc);
                if (encoding_known(low)) { free(enc); return low; }
                free(low);
                free(enc);
            }
        }
    }

    for (size_t i = 0; i + 6 <= window; i++) {
        if (strncasecmp((const char *)body + i, "<meta", 5) != 0) continue;
        size_t j = i + 5;
        while (j < window && body[j] != '>') j++;
        if (j >= window) continue;
        for (size_t k = i + 5; k + 7 < j; k++) {
            if (strncasecmp((const char *)body + k, "content", 7) != 0) continue;
            size_t q = k + 7;
            while (q < j && is_space_byte((unsigned char)body[q])) q++;
            if (q >= j || body[q] != '=') continue;
            q++;
            while (q < j && is_space_byte((unsigned char)body[q])) q++;
            if (q >= j || (body[q] != '"' && body[q] != '\'')) continue;
            char quote = (char)body[q];
            size_t vs = q + 1;
            size_t ve = vs;
            while (ve < j && body[ve] != (unsigned char)quote) ve++;
            for (size_t m = vs; m + 7 <= ve; m++) {
                if (strncasecmp((const char *)body + m, "charset", 7) != 0) continue;
                size_t z = m + 7;
                while (z < ve && is_space_byte((unsigned char)body[z])) z++;
                if (z >= ve || body[z] != '=') continue;
                z++;
                while (z < ve && is_space_byte((unsigned char)body[z])) z++;
                size_t es = z;
                while (z < ve && (isalnum((unsigned char)body[z]) || body[z] == '-' || body[z] == '_')) z++;
                if (z > es) {
                    char *enc = xstrndup((const char *)body + es, z - es);
                    char *low = str_lower(enc);
                    if (encoding_known(low)) { free(enc); return low; }
                    free(low);
                    free(enc);
                }
            }
        }
    }
    return xstrdup("utf-8");
}
